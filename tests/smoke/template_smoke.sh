#!/usr/bin/env bash
# :KeymapHelper import and generate in a real TUI: the yes/no popup for a
# hand-written target, a no that leaves the file alone, a yes that writes it.
set -euo pipefail
cd "$(dirname "$0")/../.."
root=$PWD
source tests/smoke/lib.sh
tmp=$(mktemp -d)
mkdir -p "$tmp/c/nvim/lua"
cp tests/fixtures/mappings.lua "$tmp/c/nvim/lua/mappings.lua"
env_xdg=(env XDG_CONFIG_HOME="$tmp/c" XDG_DATA_HOME="$tmp/d" XDG_STATE_HOME="$tmp/s" XDG_CACHE_HOME="$tmp/x")
trap 'smoke_stop; smoke_rmdir "$tmp"' EXIT

smoke_start 100 30 "${env_xdg[@]}" nvim --clean -u tests/smoke/init.lua
smoke_keys ':KeymapHelper import' Enter
smoke_expect 'imported [0-9]+ maps and [0-9]+ raw blocks into lua/mappings.template.json'
smoke_keys ':KeymapHelper generate' Enter
smoke_expect 'was not generated by keymap-helper'
smoke_expect 'y / <CR> yes'
smoke_keys n
smoke_reject 'was not generated by keymap-helper'
smoke_expect 'generate cancelled|nothing was written'
if grep -q AUTOGENERATED "$tmp/c/nvim/lua/mappings.lua"; then
  echo "  FAIL  a no must leave the file alone"; exit 1
fi
echo "  ok    file untouched after n"
smoke_keys ':KeymapHelper generate' Enter
smoke_keys y
smoke_expect 'wrote lua/mappings.lua \(backup: lua/mappings_'
smoke_reject 'E[0-9]+:'
head -1 "$tmp/c/nvim/lua/mappings.lua" | grep -q '^-- AUTOGENERATED by keymap-helper' \
  || { echo "  FAIL  header missing"; exit 1; }
echo "  ok    header written"
smoke_keys ':KeymapHelper generate check' Enter
smoke_expect 'matches the template'
echo "template smoke: ok"
