#!/usr/bin/env bash
# Live check of the keymap template workflow with the real config tree, on a COPY.
# The copy of ~/.config/nvim (no .git) lives under a temp dir and is the whole
# XDG_CONFIG_HOME, so the real lua/mappings.lua is never touched. Needs the
# plugins already installed in ~/.local/share/nvim (symlinked by live_lib.sh).
set -u
LIVE_ISOLATE="keymap-helper"
S=${NVIM_PLUGIN_SCRIPTS:-$HOME/.config/nvim/.claude/skills/nvim-create-and-integrate-plugin/scripts}
# shellcheck source=/dev/null
source "${S}/live_lib.sh"
fail=0
# shellcheck source=tests/ready_lib.sh
source "$(dirname "$0")/../ready_lib.sh"
chk() { "$@" || fail=1; }

live_setup
CFG_SRC=$(readlink -f "${HOME}/.config/nvim")
mkdir -p "${LIVE_TMP}/cfg"
rsync -a --exclude=.git --exclude=.claude "${CFG_SRC}/" "${LIVE_TMP}/cfg/nvim/" 2>/dev/null \
  || { mkdir -p "${LIVE_TMP}/cfg/nvim"; rsync -a --exclude=.git --exclude=.claude "${CFG_SRC}/" "${LIVE_TMP}/cfg/nvim/"; }
C="${LIVE_TMP}/cfg/nvim"
# real nvim picks the copy through XDG_CONFIG_HOME
smoke_start 140 40 env XDG_CONFIG_HOME="${LIVE_TMP}/cfg" XDG_DATA_HOME="${LIVE_TMP}/data" \
  XDG_STATE_HOME="${LIVE_TMP}/state" nvim
live_wait_nvim
smoke_keys ':KeymapHelper import' Enter
sleep 1
chk smoke_expect 'imported [0-9]+ maps'
chk smoke_reject 'E[0-9]+:'
smoke_keys ':KeymapHelper generate' Enter
sleep 1
# generate over a hand-written file asks first
chk smoke_expect 'not generated by keymap-helper'
smoke_type 'n'; sleep 1
cmp -s "${CFG_SRC}/lua/mappings.lua" "${C}/lua/mappings.lua" && echo "  ok    n left the file alone" || { echo "  FAIL  n changed file"; fail=1; }
smoke_keys ':KeymapHelper generate' Enter; sleep 1
smoke_type 'y'; sleep 1
chk smoke_expect 'wrote lua/mappings.lua'
ls "${C}/lua"/mappings_*.bak >/dev/null 2>&1 && echo "  ok    backup made" || { echo "  FAIL  no backup"; fail=1; }
smoke_keys ":source ${C}/lua/mappings.lua" Enter; sleep 1
smoke_type ' km'; sleep 2
chk smoke_expect 'Custom'
chk smoke_expect 'General|Splits|LSP'
chk smoke_reject 'INSERT'
chk smoke_reject 'E[0-9]+:'
smoke_keys Escape; smoke_keys q
live_teardown
exit $fail
