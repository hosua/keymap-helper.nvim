local generate = require "keymap-helper.template.generate"
local schema = require "keymap-helper.template.schema"
local json = require "keymap-helper.template.json"

local root = vim.fn.fnamemodify(debug.getinfo(1, "S").source:gsub("^@", ""), ":p:h:h:h")
local function fixture(name)
  return table.concat(vim.fn.readfile(root .. "/tests/fixtures/template/" .. name), "\n") .. "\n"
end
local function golden_template()
  return schema.normalize(assert(json.decode(fixture "golden.template.json")))
end

describe("template generate", function()
  it("matches the golden file", function()
    eq(fixture "golden.lua", generate.render(golden_template()))
  end)

  it("is idempotent: json -> lua -> same lua, and a second write changes nothing", function()
    local t = golden_template()
    eq(generate.render(t), generate.render(schema.normalize(assert(json.decode(json.encode(t))))))
    local dir = tmpdir()
    local target = dir .. "/lua/mappings.lua"
    local first = assert(generate.write(t, target, { now = 1 }))
    eq(true, first.changed)
    local second = assert(generate.write(t, target, { now = 2 }))
    eq(false, second.changed)
    eq(fixture "golden.lua", table.concat(vim.fn.readfile(target), "\n") .. "\n")
    eq({ "mappings.lua" }, vim.tbl_map(vim.fs.basename, vim.fn.glob(dir .. "/lua/*", false, true)))
  end)

  it("puts the five header lines at the very top", function()
    local lines = vim.split(generate.render(schema.new()), "\n")
    eq("-- AUTOGENERATED by keymap-helper from lua/mappings.template.json.", lines[1])
    eq("-- DO NOT EDIT THIS FILE: your changes are overwritten the next time it is generated.", lines[2])
    eq(
      "-- To change a keymap: run :KeymapHelper edit, or edit the template JSON (lua/mappings.template.json),",
      lines[3]
    )
    eq("-- then run :KeymapHelper generate. Every generate keeps a backup of the old file.", lines[4])
    eq("-- To undo: copy the newest mappings_<YYYY_MM_DD_hh:mm:ss>.bak over this file.", lines[5])
    eq("", lines[6])
  end)

  it("strips the header and nothing else", function()
    local text = generate.render(golden_template())
    local body = generate.strip_header(text)
    ok(vim.startswith(body, 'require "nvchad.mappings"'))
    eq("local x = 1\n", generate.strip_header "local x = 1\n")
  end)

  it("draws the box 80 columns wide with the title inside", function()
    local box = vim.split(generate.box "General", "\n")
    eq(3, #box)
    for _, l in ipairs(box) do
      eq(80, vim.fn.strdisplaywidth(l))
    end
    ok(box[2]:find("│ General ", 1, true))
    -- group_by = "header" must find it with the default pattern.
    eq("General", box[2]:match(require("keymap-helper.config").defaults.header_pattern))
  end)

  it("writes all the typed options in a fixed order", function()
    local call = generate.map_call {
      modes = { "n" },
      lhs = "a",
      rhs = "b",
      opts = { silent = true, desc = "d", buffer = 0, remap = false },
      opts_raw = { zz = "1", aa = "f()" },
    }
    eq('map("n", "a", "b", { desc = "d", silent = true, remap = false, buffer = 0, aa = f(), zz = 1 })', call)
  end)

  it("quotes awkward strings so they load back unchanged", function()
    for _, s in ipairs { 'a"b', "a\\b", "a\nb", "tab\there", "'", "\1" } do
      eq(s, load("return " .. generate.quote(s))())
    end
  end)

  it("refuses an invalid template without touching anything", function()
    local dir = tmpdir()
    local target = dir .. "/mappings.lua"
    vim.fn.writefile({ "keep me" }, target)
    local t = golden_template()
    t.entries[1].lhs = ""
    local res, err = generate.write(t, target, { now = 1 })
    eq(nil, res)
    ok(err:find("nothing was written", 1, true), err)
    eq({ "keep me" }, vim.fn.readfile(target))
    eq({ "mappings.lua" }, vim.tbl_map(vim.fs.basename, vim.fn.glob(dir .. "/*", false, true)))
  end)

  it("writes the backup before the target, with the old contents", function()
    local dir = tmpdir()
    local target = dir .. "/mappings.lua"
    vim.fn.writefile({ "old" }, target)
    local res = assert(generate.write(golden_template(), target, { now = os.time() }))
    eq({ "old" }, vim.fn.readfile(res.backup))
    ok(generate.has_header(table.concat(vim.fn.readfile(target), "\n")))
  end)

  it("skips the backup when backups are off", function()
    local dir = tmpdir()
    local target = dir .. "/mappings.lua"
    vim.fn.writefile({ "old" }, target)
    local res = assert(generate.write(golden_template(), target, { backups = false }))
    eq(nil, res.backup)
    eq({ "mappings.lua" }, vim.tbl_map(vim.fs.basename, vim.fn.glob(dir .. "/*", false, true)))
  end)

  it("check reports a difference and then agreement", function()
    local dir = tmpdir()
    local target = dir .. "/mappings.lua"
    local t = golden_template()
    local in_sync, why = generate.check(t, target)
    eq(false, in_sync)
    ok(why:find("does not exist", 1, true))
    assert(generate.write(t, target))
    eq(true, (generate.check(t, target)))
    vim.fn.writefile({ "-- edited" }, target)
    eq(false, (generate.check(t, target)))
  end)
end)
