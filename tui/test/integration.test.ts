// The TUI's state and the real Lua scripts together, in a throwaway root:
// kh-import, a few edits through the reducer, save (kh-template save, then
// kh-generate), and the nvim keymaps must be what they were before.
import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createBridge, PLUGIN_ROOT } from "../src/bridge.ts";
import { init, type State, update } from "../src/state.ts";
import type { Loaded } from "../src/types.ts";
import { press, typed } from "./helpers.ts";

const FIXTURE = join(PLUGIN_ROOT, "tests/fixtures/user_mappings.lua");
const DUMP = join(PLUGIN_ROOT, "tests/integration/dump_keymaps.lua");

let tmp: string;
let env: Record<string, string>;

beforeAll(() => {
  tmp = mkdtempSync(join(tmpdir(), "kh-tui-"));
  env = {
    XDG_CONFIG_HOME: join(tmp, "xdg/config"),
    XDG_DATA_HOME: join(tmp, "xdg/data"),
    XDG_STATE_HOME: join(tmp, "xdg/state"),
    XDG_CACHE_HOME: join(tmp, "xdg/cache"),
  };
});
afterAll(() => rmSync(tmp, { recursive: true, force: true }));

function newRoot(name: string): string {
  const root = join(tmp, name);
  mkdirSync(join(root, "lua"), { recursive: true });
  cpSync(FIXTURE, join(root, "lua/mappings.lua"));
  return root;
}

/** Global keymaps a file creates, loaded in a child nvim with no config. */
async function keymaps(file: string): Promise<unknown[]> {
  const proc = Bun.spawn(["nvim", "--headless", "-u", "NONE", "-l", DUMP, file], {
    stdout: "pipe",
    stderr: "pipe",
    env: { ...process.env, ...env },
  });
  const [out, err, code] = await Promise.all([new Response(proc.stdout).text(), new Response(proc.stderr).text(), proc.exited]);
  expect(code, err).toBe(0);
  const sorted = (JSON.parse(out) as unknown[]).map((m) => JSON.stringify(m)).sort();
  return sorted;
}

const baks = (root: string, prefix: string) => readdirSync(join(root, "lua")).filter((f) => f.startsWith(prefix) && f.endsWith(".bak"));

describe("import, categorize, save, generate", () => {
  test("the generated file creates the same keymaps as the hand-written one", async () => {
    const root = newRoot("a");
    const bridge = createBridge({ root, env });

    // No template yet: the TUI offers an import, and the bridge does it.
    const first = await bridge.show();
    expect(first.status).toBe("missing");
    expect(first.status === "missing" && first.source_exists).toBe(true);
    await bridge.importTemplate(false);
    const shown = (await bridge.show()) as Loaded;
    expect(shown.status).toBe("ready");
    expect(shown.doc.categories.map((c) => c.id)).toEqual(["uncategorized"]);
    expect(Object.keys(shown.calls).length).toBeGreaterThan(50);

    // Categorize through the state: two maps to a new category, one raw block to another.
    let s: State = init(shown, { w: 140, h: 40 });
    let r = press(s, "l", "v", "j", "v", "m", ...typed("Basics"), "return");
    s = r.s;
    expect(s.ui.message?.text).toContain('new category "Basics"');
    r = press(s, "G", "m", ...typed("Last"), "return");
    s = r.s;
    r = press(s, "h", "j", "<");
    s = r.s;
    r = press(s, "w", "y");
    expect(r.fx).toHaveLength(1);
    const fx = r.fx[0];
    if (fx?.type !== "save") throw new Error("expected a save effect");

    const before = await keymaps(join(root, "lua/mappings.lua"));
    const result = await bridge.save(fx.plan);
    expect(result.generateError).toBeUndefined();
    expect(result.targetStatus).toBe("written");
    expect(result.templateBackup).toMatch(/mappings\.template_\d{4}_\d\d_\d\d_\d\d:\d\d:\d\d(_\d+)?\.bak$/);
    expect(result.targetBackup).toMatch(/mappings_\d{4}_\d\d_\d\d_\d\d:\d\d:\d\d(_\d+)?\.bak$/);
    expect(existsSync(result.templateBackup as string)).toBe(true);
    expect(existsSync(result.targetBackup as string)).toBe(true);

    // The hand-written file was backed up byte for byte, and the new one is generated.
    expect(readFileSync(result.targetBackup as string, "utf8")).toBe(readFileSync(FIXTURE, "utf8"));
    const generated = readFileSync(join(root, "lua/mappings.lua"), "utf8");
    expect(generated.startsWith("-- AUTOGENERATED by keymap-helper")).toBe(true);
    expect(generated).toContain("│ Basics");
    expect(generated).toContain("│ Last");

    // The nvim keymap set is unchanged by moving things between categories.
    const after = await keymaps(join(root, "lua/mappings.lua"));
    expect(after).toEqual(before);

    // Reloading shows the categories that were saved, and nothing is unsaved.
    const again = (await bridge.show()) as Loaded;
    expect(again.doc.categories.map((c) => c.title).sort()).toEqual(["Basics", "Last", "Uncategorized"]);
    expect(again.target_generated).toBe(true);
    const [fresh] = update(init(again, { w: 100, h: 30 }), { type: "key", key: "w" });
    expect(fresh.ui.message?.text).toBe("nothing to save");

    // A second save creates a second pair of backups, never overwriting the first.
    const second = press(fresh, "l", "m", "return", "w", "y").fx[0];
    if (second?.type !== "save") throw new Error("expected a save effect");
    const r2 = await bridge.save(second.plan);
    expect(r2.templateBackup).not.toBe(result.templateBackup);
    expect(baks(root, "mappings.template_").length).toBe(2);
    expect(await keymaps(join(root, "lua/mappings.lua"))).toEqual(before);
  });

  test("the keep_headers preview reads the file and writes nothing", async () => {
    const root = newRoot("b");
    const bridge = createBridge({ root, env });
    await bridge.importTemplate(false);
    const flat = (await bridge.show()) as Loaded;
    const before = readFileSync(join(root, "lua/mappings.template.json"), "utf8");
    const preview = await bridge.preview(true);
    expect(preview.status).toBe("preview");
    expect(preview.doc.categories.length).toBeGreaterThan(flat.doc.categories.length);
    expect(preview.doc.categories.map((c) => c.title)).toContain("General");
    expect(readFileSync(join(root, "lua/mappings.template.json"), "utf8")).toBe(before);
    expect(baks(root, "mappings.template_")).toEqual([]);

    // Applying it goes through kh-import, which backs up the old template.
    await bridge.importTemplate(true);
    expect(baks(root, "mappings.template_")).toHaveLength(1);
    const applied = (await bridge.show()) as Loaded;
    expect(applied.doc.categories.map((c) => c.title)).toEqual(preview.doc.categories.map((c) => c.title));
  });

  test("entries the user did not touch are written exactly as before", async () => {
    const root = newRoot("c");
    const bridge = createBridge({ root, env });
    await bridge.importTemplate(false);
    const shown = (await bridge.show()) as Loaded;
    const templateBefore = JSON.parse(readFileSync(join(root, "lua/mappings.template.json"), "utf8")) as { entries: { id: string }[] };
    const move = press(init(shown, { w: 100, h: 30 }), "l", "m", ...typed("One"), "return", "w", "y").fx[0];
    if (move?.type !== "save") throw new Error("expected a save effect");
    await bridge.save(move.plan);
    const templateAfter = JSON.parse(readFileSync(join(root, "lua/mappings.template.json"), "utf8")) as {
      entries: { id: string; category: string }[];
    };
    const moved = templateAfter.entries.filter((e) => e.category !== "uncategorized");
    expect(moved).toHaveLength(1);
    for (const e of templateBefore.entries) {
      const now = templateAfter.entries.find((x) => x.id === e.id) as Record<string, unknown>;
      const { category: _a, ...was } = e as Record<string, unknown>;
      const { category: _b, ...is } = now;
      expect(is).toEqual(was);
    }
  });

  test("a bad plan fails with the Lua message and leaves the template alone", async () => {
    const root = newRoot("d");
    const bridge = createBridge({ root, env });
    await bridge.importTemplate(false);
    const before = readFileSync(join(root, "lua/mappings.template.json"), "utf8");
    await expect(bridge.save({ categories: [{ id: "uncategorized", title: "Uncategorized" }], order: [] })).rejects.toThrow(
      /leaves out entry/,
    );
    expect(readFileSync(join(root, "lua/mappings.template.json"), "utf8")).toBe(before);
  });

  test("a missing mappings file and a broken template are reported, not thrown away", async () => {
    const root = join(tmp, "e");
    mkdirSync(join(root, "lua"), { recursive: true });
    const bridge = createBridge({ root, env });
    const m = await bridge.show();
    expect(m.status === "missing" && m.source_exists).toBe(false);
    await Bun.write(join(root, "lua/mappings.template.json"), "{ nope");
    await expect(bridge.show()).rejects.toThrow(/not valid JSON/);
  });
});
